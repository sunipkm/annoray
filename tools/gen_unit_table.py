"""Generate crates/annoray-units/src/table.rs from the UDUNITS-2 XML database.

Usage (from the repository root):

    python3 tools/gen_unit_table.py <dir-with-udunits2-*.xml> > crates/annoray-units/src/table.rs

The XML files are lib/udunits2-{base,derived,accepted,common,prefixes}.xml from
https://github.com/Unidata/UDUNITS-2. The output is committed, so the build never needs them.
"""

import os
import sys
import xml.etree.ElementTree as ET

SYSTEMS = ["base", "derived", "accepted", "common"]
BASE_DIMS = {"m": "Length", "kg": "Mass", "s": "Time", "A": "Current", "K": "Temperature",
             "mol": "Amount", "cd": "Luminosity"}



def req(text: str | None) -> str:
    """The stripped text of an XML element the UDUNITS database always fills in."""
    if text is None:
        raise SystemExit("unexpected empty element in the UDUNITS database")
    return text.strip()

def plural(singular):
    """UDUNITS' automatic English plural (lib/xml.c: ut_form_plural)."""
    if singular.endswith(("s", "x", "z", "ch", "sh")):
        return singular + "es"
    if len(singular) > 1 and singular.endswith("y") and singular[-2] not in "aeiou":
        return singular[:-1] + "ies"
    return singular + "s"


def names_of(elem):
    out = []
    for n in elem.findall("name"):
        s = n.findtext("singular").strip()
        out.append(s)
        if n.find("noplural") is not None:
            continue
        p = n.findtext("plural")
        out.append(p.strip() if p else plural(s))
    return out


def rs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rs_list(xs):
    return "&[" + ", ".join(rs(x) for x in xs) + "]"


def main(d):
    print("// @generated by tools/gen_unit_table.py from the UDUNITS-2 XML database")
    print("// (https://github.com/Unidata/UDUNITS-2, Copyright UCAR/Unidata). Do not edit by hand.")
    print()
    print("use crate::registry::{Def, PrefixEntry, UnitEntry};")
    print("use crate::BaseDim;")
    print()
    print("pub(crate) static UNITS: &[UnitEntry] = &[")
    for sysname in SYSTEMS:
        root = ET.parse(os.path.join(d, f"udunits2-{sysname}.xml")).getroot()
        for u in root.iter("unit"):
            names = names_of(u)
            symbols = [req(s.text) for s in u.findall("symbol")]
            aliases = u.find("aliases")
            if aliases is not None:
                names += names_of(aliases)
                symbols += [req(s.text) for s in aliases.findall("symbol")]
            if u.find("base") is not None:
                definition = f"Def::Base(BaseDim::{BASE_DIMS[symbols[0]]})"
            elif u.find("dimensionless") is not None:
                if symbols != ["rad"]:
                    raise SystemExit(f"unexpected dimensionless unit {names} {symbols}")
                definition = "Def::Base(BaseDim::Angle)"  # angle is a first-class dimension here
            elif "pi" in names:
                definition = "Def::Pi"  # exact π instead of UDUNITS' 31-digit decimal
            else:
                definition = f"Def::Expr({rs(req(u.findtext('def')))})"
            print(f"    UnitEntry {{ def: {definition}, names: {rs_list(names)}, symbols: {rs_list(symbols)} }},")
    print("];")
    print()
    print("pub(crate) static PREFIXES: &[PrefixEntry] = &[")
    root = ET.parse(os.path.join(d, "udunits2-prefixes.xml")).getroot()
    for p in root.iter("prefix"):
        value = req(p.findtext("value"))
        names = [req(n.text) for n in p.findall("name")]
        symbols = [req(s.text) for s in p.findall("symbol")]
        print(f"    PrefixEntry {{ value: {rs(value)}, names: {rs_list(names)}, symbols: {rs_list(symbols)} }},")
    print("];")


if __name__ == "__main__":
    main(sys.argv[1])
